"""Synthetic validation matrix. Never presented as human-recording validation."""
import json
import sys
import tempfile
import time
import wave
from pathlib import Path
import numpy as np
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
import speech
import audio_analysis as a
sys.path.insert(0,str(Path(__file__).parent))
from benchmark_ser import peak_mb

speech.MODEL_NAME=str(next((Path.home()/'.cache/huggingface/hub/models--Systran--faster-whisper-base/snapshots').iterdir()))
speech.get_model()
from faster_whisper.vad import get_vad_model
get_vad_model()
fixture=Path(__file__).parent/'chinese-fixture.wav'
pcm,_=a._decode(fixture,time.monotonic()+15)
extra=Path(sys.argv[1]) if len(sys.argv)>1 else None

def write(path, samples):
    with wave.open(str(path),'wb') as f:
        f.setnchannels(1);f.setsampwidth(2);f.setframerate(16000)
        f.writeframes((np.clip(samples,-1,1)*32767).astype('<i2').tobytes())

results=[]
with tempfile.TemporaryDirectory() as directory:
    cases={'ordinary':pcm,'pauses':np.concatenate([pcm[:80000],np.zeros(32000),pcm[80000:]]),
           'silence_60s':np.zeros(960000),'noise':pcm+np.random.default_rng(10).normal(0,.08,len(pcm)),
           'short':pcm[16000:17600],'low_volume':pcm*.01,
           'long_120s':np.tile(pcm,12)[:1920000],
           'noise_only':np.random.default_rng(19).normal(0,.08,160000)}
    if extra:
        for name in ['mixed','fast','slow']:cases[name]=a._decode(extra/(name+'.wav'),time.monotonic()+15)[0]
    for name,samples in cases.items():
        path=Path(directory)/(name+'.wav');write(path,samples)
        # Long-answer performance is measured without another costly full ASR pass.
        if name=='long_120s':text='';text_source='ASR skipped for performance probe; rates unavailable'
        else:text,_=speech.transcribe(path);text_source='actual faster-whisper base'
        result=a.analyze_audio(path,text)
        results.append({'case':name,'fixture_type':'synthetic speech or generated signal, not human',
                        'asr_text':text,'text_source':text_source,'analysis':result})
        print(name,result['status'],result.get('processing_ms'),flush=True)
report={'tests':results,'peak_working_set_mb':peak_mb(),
        'note':'No human audio available. Fast/slow fixtures generated by SAPI speaking rate; noise/pauses/gain explicitly modified.'}
target=Path(__file__).resolve().parents[1]/'docs/acoustic-benchmark.json'
target.write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
print('Saved',target,'peak MB',report['peak_working_set_mb'])
